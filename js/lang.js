let currentLang = localStorage.getItem('vtt_lang') || 'it';

function translateNode(node) {
    if (node.nodeType === 3) { // Text node
        let text = node.nodeValue.trim();
        if (text === "" || text.length <= 1) return;
        
        // Save original if not saved
        if (!node.originalText) {
            node.originalText = text;
        }
        
        let targetText = node.originalText; // Default to Italian
        
        if (currentLang === 'en') {
            // Find English translation
            if (dict[node.originalText]) {
                targetText = dict[node.originalText];
            } else {
                // Try ignoring trailing spaces/colons
                let clean = node.originalText.replace(/:$/, '').trim();
                if (dict[clean]) {
                    targetText = dict[clean] + (node.originalText.endsWith(':') ? ':' : '');
                }
            }
        }
        
        if (node.nodeValue.trim() !== targetText) {
            node.nodeValue = node.nodeValue.replace(node.nodeValue.trim(), targetText);
        }
    } else if (node.nodeType === 1) { // Element node
        if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
        
        // Translate placeholders
        if (node.hasAttribute('placeholder')) {
            if (!node.originalPlaceholder) node.originalPlaceholder = node.getAttribute('placeholder');
            let target = node.originalPlaceholder;
            if (currentLang === 'en' && dict[target]) target = dict[target];
            if (node.getAttribute('placeholder') !== target) node.setAttribute('placeholder', target);
        }
        
        // Translate title
        if (node.hasAttribute('title')) {
            if (!node.originalTitle) node.originalTitle = node.getAttribute('title');
            let target = node.originalTitle;
            if (currentLang === 'en' && dict[target]) target = dict[target];
            if (node.getAttribute('title') !== target) node.setAttribute('title', target);
        }

        // Recursion
        for (let child of node.childNodes) {
            translateNode(child);
        }
    }
}

function applyLanguage() {
    translateNode(document.body);
    
    const btn = document.getElementById('lang-toggle');
    if (btn) {
        btn.innerText = currentLang === 'it' ? '🇮🇹 IT' : '🇬🇧 EN';
    }
}

function toggleLanguage() {
    currentLang = currentLang === 'it' ? 'en' : 'it';
    localStorage.setItem('vtt_lang', currentLang);
    applyLanguage();
}

const observer = new MutationObserver((mutations) => {
    let shouldTranslate = false;
    for (let mutation of mutations) {
        if (mutation.addedNodes.length > 0) {
            shouldTranslate = true;
            break;
        }
    }
    if (shouldTranslate) {
        observer.disconnect();
        applyLanguage();
        observer.observe(document.body, { childList: true, subtree: true });
    }
});

